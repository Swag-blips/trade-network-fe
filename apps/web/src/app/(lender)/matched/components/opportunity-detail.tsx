"use client";

import { useEffect, useRef, useState } from "react";
import { HugeiconsIcon } from "@hugeicons/react";
import {
  ArrowDown01Icon,
  ArrowLeft01Icon,
  ArrowRight01Icon,
  Cancel01Icon,
  DashboardSpeed01Icon,
  Loading01Icon,
  Payment02Icon,
  ReceiptTextIcon,
  UnavailableIcon,
  WarehouseIcon,
  Store02Icon,
} from "@hugeicons/core-free-icons";
import type { IconSvgElement } from "@hugeicons/react";
import { Button } from "@repo/ui/button";
import { InitialsAvatar } from "@/components/avatars";
import { TaiAgent } from "@/components/tai-agent";
import { TradeRoom } from "./trade-room";
import type { Opportunity, OpportunityDetail } from "../types/opportunity";

const METRIC_ICONS: IconSvgElement[] = [
  Payment02Icon,
  ReceiptTextIcon,
  DashboardSpeed01Icon,
  Loading01Icon,
];

function Overview({ detail }: { detail: OpportunityDetail }) {
  return (
    <div className="flex flex-col gap-lg">
      <h3 className="font-brand text-[1.5rem]/[1.5] font-medium text-grey-900">
        Opportunity details
      </h3>

      <div className="flex flex-wrap items-stretch gap-md">
        {detail.metrics.map((metric, index) => (
          <div
            key={metric.id}
            className="flex min-w-[205px] flex-1 flex-col gap-md overflow-hidden rounded-lg border border-grey-100 bg-white px-md py-2.5"
          >
            <span className="flex size-8 items-center justify-center rounded-xl bg-evergreen-100">
              <HugeiconsIcon
                icon={METRIC_ICONS[index % METRIC_ICONS.length]!}
                size={20}
                className="text-evergreen-700"
              />
            </span>
            <span className="flex flex-col gap-1">
              <span className="text-body-sm text-grey-800">{metric.label}</span>
              <span className="font-brand text-[1.25rem]/[1.3] font-medium tracking-[0.16px] text-grey-900">
                {metric.value}
              </span>
            </span>
          </div>
        ))}
      </div>

      <section className="flex flex-col gap-md overflow-hidden rounded-lg border border-[#92bbfd] bg-white p-sm">
        <div className="flex w-full items-center gap-sm">
          <span className="flex min-w-0 flex-1 items-center gap-xs">
            <TaiAgent size="xs" />
            <span className="font-sans text-body font-medium text-grey-900">
              Summary
            </span>
          </span>
          <span className="flex-none rounded-sm bg-grey-100 px-xs py-0.5 text-caption/[normal] font-medium text-grey-500">
            Generated by TAI
          </span>
        </div>
        <hr className="border-grey-100" />
        <div className="flex flex-col gap-xs">
          <p className="font-sans text-[1.25rem]/[1.5] font-medium text-grey-900">
            {detail.summary.verdict}
          </p>
          <p className="text-body text-grey-800">{detail.summary.body}</p>
        </div>
      </section>
    </div>
  );
}

export function OpportunityDetailModal({
  item,
  detail,
  onClose,
  onPrev,
  onNext,
}: {
  item: Opportunity;
  detail: OpportunityDetail;
  onClose: () => void;
  onPrev?: () => void;
  onNext?: () => void;
}) {
  const ref = useRef<HTMLDialogElement>(null);
  const [tab, setTab] = useState<"Details" | "TradeRoom">("Details");

  useEffect(() => {
    const dialog = ref.current;
    if (dialog && !dialog.open) dialog.showModal();
  }, []);

  return (
    <dialog
      ref={ref}
      aria-labelledby="opportunity-title"
      onCancel={(event) => {
        event.preventDefault();
        onClose();
      }}
      className="m-auto h-[791px] max-h-[calc(100vh-2.5rem)] w-[1244px] max-w-[calc(100vw-2.25rem)] overflow-hidden rounded-xl bg-white p-0 backdrop:bg-grey-900/40"
    >
      <div className="flex h-full flex-col">
        <header className="flex flex-none items-center gap-lg border-b border-grey-100 px-lg py-2.5">
          <div className="flex min-w-0 flex-1 items-center gap-xs">
            <InitialsAvatar initials={item.initials} size={32} />
            <h2
              id="opportunity-title"
              className="truncate font-sans text-body font-medium text-grey-900"
            >
              {item.name}
            </h2>
          </div>
          <div className="flex flex-none items-center gap-xs">
            <button
              type="button"
              aria-label="Previous opportunity"
              disabled={!onPrev}
              onClick={onPrev}
              className="flex size-6 items-center justify-center rounded-full text-grey-900 hover:bg-grey-100 disabled:text-grey-300"
            >
              <HugeiconsIcon icon={ArrowLeft01Icon} size={16} />
            </button>
            <button
              type="button"
              aria-label="Next opportunity"
              disabled={!onNext}
              onClick={onNext}
              className="flex size-6 items-center justify-center rounded-full text-grey-900 hover:bg-grey-100 disabled:text-grey-300"
            >
              <HugeiconsIcon icon={ArrowRight01Icon} size={16} />
            </button>
            <span aria-hidden className="mx-xs h-3.5 w-px bg-grey-200" />
            <button
              type="button"
              aria-label="Close"
              onClick={onClose}
              className="text-grey-900 hover:text-grey-600"
            >
              <HugeiconsIcon icon={Cancel01Icon} size={20} />
            </button>
          </div>
        </header>

        <div className="flex min-h-px flex-1">
          <div className="flex min-w-0 flex-1 flex-col border-r border-grey-100">
            <div
              role="tablist"
              aria-label="Opportunity sections"
              className="flex flex-none items-center gap-md border-b border-grey-100 px-lg"
            >
              {(["Details", "TradeRoom"] as const).map((name) => {
                const active = tab === name;
                return (
                  <button
                    key={name}
                    role="tab"
                    aria-selected={active}
                    onClick={() => setTab(name)}
                    className={`-mb-px border-b-2 px-1 py-sm font-sans text-body transition-colors motion-reduce:transition-none ${
                      active
                        ? "border-evergreen-600 font-medium text-grey-900"
                        : "border-transparent text-grey-500 hover:text-grey-900"
                    }`}
                  >
                    {name}
                  </button>
                );
              })}
            </div>
            <div className="min-h-px flex-1 overflow-y-auto px-lg py-lg">
              {tab === "Details" ? (
                <Overview detail={detail} />
              ) : (
                <TradeRoom item={item} detail={detail} />
              )}
            </div>
          </div>

          <aside className="flex w-[327px] flex-none flex-col gap-lg p-lg">
            <div className="flex flex-col items-center gap-lg">
              <InitialsAvatar initials={item.initials} size={80} />
              <div className="flex flex-col items-center gap-1">
                <p className="font-brand text-[1.25rem]/[1.5] font-medium text-grey-900">
                  {item.name}
                </p>
                <span className="flex items-center gap-1">
                  <HugeiconsIcon
                    icon={
                      item.kind === "Distributor" ? Store02Icon : WarehouseIcon
                    }
                    size={16}
                    className="text-grey-800"
                  />
                  <span className="text-body-sm/[normal] text-grey-800">
                    {item.kind}
                  </span>
                </span>
              </div>
            </div>
            <div className="flex flex-col gap-md">
              <Button
                size="lg"
                className="w-full"
                trailingIcon={<HugeiconsIcon icon={ArrowDown01Icon} />}
              >
                Take action
              </Button>
              <Button
                variant="outline"
                size="form"
                className="w-full"
                leadingIcon={<HugeiconsIcon icon={UnavailableIcon} />}
              >
                Not interested
              </Button>
            </div>
          </aside>
        </div>
      </div>
    </dialog>
  );
}
